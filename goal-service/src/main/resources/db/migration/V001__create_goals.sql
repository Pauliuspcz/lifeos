CREATE TABLE goals (
                       id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       user_id            BIGINT        NOT NULL,
                       title              VARCHAR(255)  NOT NULL,
                       description        VARCHAR(1000),
                       period             VARCHAR(20)   NOT NULL,
                       times_per_period   INT           NOT NULL,
                       amount_per_session NUMERIC(10, 2),
                       unit               VARCHAR(30),
                       status             VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
                       template_id        BIGINT,
                       version            BIGINT        NOT NULL DEFAULT 0,
                       created_at         TIMESTAMP     NOT NULL,
                       updated_at         TIMESTAMP     NOT NULL,
                       archived_at        TIMESTAMP,
                       CONSTRAINT ck_goals_period CHECK (period IN ('DAILY', 'WEEKLY', 'MONTHLY')),
                       CONSTRAINT ck_goals_status CHECK (status IN ('ACTIVE', 'ARCHIVED')),
                       CONSTRAINT ck_goals_times_per_period CHECK (times_per_period > 0),
                       CONSTRAINT ck_goals_amount CHECK (amount_per_session IS NULL OR amount_per_session > 0)
);

CREATE INDEX idx_goals_user_status ON goals (user_id, status);