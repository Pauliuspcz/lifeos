CREATE TABLE categories (
                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code        VARCHAR(50)  NOT NULL UNIQUE,
                            name        VARCHAR(100) NOT NULL,
                            description VARCHAR(500),
                            icon_key    VARCHAR(50),
                            color       VARCHAR(7),
                            sort_order  INT          NOT NULL DEFAULT 0
);

CREATE TABLE directions (
                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code        VARCHAR(50)  NOT NULL UNIQUE,
                            name        VARCHAR(100) NOT NULL,
                            description VARCHAR(500),
                            icon_key    VARCHAR(50),
                            color       VARCHAR(7),
                            sort_order  INT          NOT NULL DEFAULT 0
);

CREATE TABLE goal_templates (
                                id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                category_id            BIGINT       NOT NULL REFERENCES categories (id),
                                title                  VARCHAR(255) NOT NULL,
                                description            VARCHAR(1000),
                                goal_type              VARCHAR(20)  NOT NULL,
                                tracking_type          VARCHAR(20)  NOT NULL,
                                default_period         VARCHAR(20),
                                default_times_per_period INT,
                                default_target_amount  NUMERIC(10, 2),
                                default_unit           VARCHAR(50),
                                default_target_time    TIME,
                                difficulty             VARCHAR(20),
                                icon_key               VARCHAR(50),
                                color                  VARCHAR(7),
                                sort_order             INT          NOT NULL DEFAULT 0,
                                active                 BOOLEAN      NOT NULL DEFAULT TRUE,
                                CONSTRAINT ck_tpl_goal_type CHECK (goal_type IN ('HABIT', 'TARGET', 'EVENT', 'OTHER')),
                                CONSTRAINT ck_tpl_tracking CHECK (tracking_type IN
                                                                  ('CHECK', 'COUNT', 'AMOUNT', 'DURATION', 'TIME_TARGET', 'LIMIT', 'EVENT')),
                                CONSTRAINT ck_tpl_difficulty CHECK (difficulty IS NULL OR difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);

CREATE TABLE direction_templates (
                                     direction_id BIGINT NOT NULL REFERENCES directions (id),
                                     template_id  BIGINT NOT NULL REFERENCES goal_templates (id),
                                     PRIMARY KEY (direction_id, template_id)
);

CREATE INDEX idx_templates_category ON goal_templates (category_id);

