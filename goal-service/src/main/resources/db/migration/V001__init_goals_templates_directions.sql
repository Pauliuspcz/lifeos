CREATE TABLE categories (
                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code        VARCHAR(50)  NOT NULL UNIQUE,
                            name        VARCHAR(100) NOT NULL,
                            description VARCHAR(500),
                            icon_key    VARCHAR(50),
                            color       VARCHAR(7),
                            sort_order  INT          NOT NULL DEFAULT 0
);

CREATE TABLE directions (
                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            category_id BIGINT       NOT NULL REFERENCES categories (id),
                            code        VARCHAR(50)  NOT NULL UNIQUE,
                            name        VARCHAR(100) NOT NULL,
                            description VARCHAR(500),
                            icon_key    VARCHAR(50),
                            color       VARCHAR(7),
                            sort_order  INT          NOT NULL DEFAULT 0,
                            CONSTRAINT uq_directions_id_category UNIQUE (id, category_id)
);

CREATE TABLE goal_templates (
                                id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                code                     VARCHAR(60)    NOT NULL UNIQUE,
                                category_id              BIGINT         NOT NULL REFERENCES categories (id),
                                direction_id             BIGINT         NOT NULL,
                                title                    VARCHAR(255)   NOT NULL,
                                description              VARCHAR(1000),
                                tracking_type            VARCHAR(20)    NOT NULL,
                                default_period           VARCHAR(20),
                                default_times_per_period INT,
                                default_target_amount    NUMERIC(12, 2),
                                default_unit             VARCHAR(50),
                                default_target_time      TIME,
                                default_duration_days    INT,
                                outdoor                  BOOLEAN        NOT NULL DEFAULT FALSE,
                                difficulty               VARCHAR(20),
                                icon_key                 VARCHAR(50),
                                color                    VARCHAR(7),
                                sort_order               INT            NOT NULL DEFAULT 0,
                                active                   BOOLEAN        NOT NULL DEFAULT TRUE,
                                CONSTRAINT fk_templates_direction_category
                                    FOREIGN KEY (direction_id, category_id) REFERENCES directions (id, category_id),
                                CONSTRAINT ck_tpl_tracking CHECK (tracking_type IN ('CHECK', 'AMOUNT')),
                                CONSTRAINT ck_tpl_period CHECK (default_period IS NULL OR default_period IN ('DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY')),
                                CONSTRAINT ck_tpl_difficulty CHECK (difficulty IS NULL OR difficulty IN ('EASY', 'MEDIUM', 'HARD')),
                                CONSTRAINT ck_tpl_times CHECK (default_times_per_period IS NULL OR default_times_per_period > 0),
                                CONSTRAINT ck_tpl_amount CHECK (default_target_amount IS NULL OR default_target_amount > 0),
                                CONSTRAINT ck_tpl_duration CHECK (default_duration_days IS NULL OR default_duration_days > 0),
                                CONSTRAINT ck_tpl_shape CHECK (
                                    (tracking_type = 'CHECK' AND default_period IS NOT NULL AND default_times_per_period IS NOT NULL)
                                        OR
                                    (tracking_type = 'AMOUNT' AND default_target_amount IS NOT NULL AND default_unit IS NOT NULL)
                                    )
);

CREATE INDEX idx_directions_category ON directions (category_id);
CREATE INDEX idx_templates_category  ON goal_templates (category_id);
CREATE INDEX idx_templates_direction ON goal_templates (direction_id);

CREATE TABLE goals (
                       id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       user_id          BIGINT         NOT NULL,
                       title            VARCHAR(255)   NOT NULL,
                       description      VARCHAR(1000),
                       tracking_type    VARCHAR(20)    NOT NULL DEFAULT 'CHECK',
                       period           VARCHAR(20),
                       times_per_period INT,
                       target_amount    NUMERIC(12, 2),
                       unit             VARCHAR(50),
                       target_time      TIME,
                       start_date       DATE,
                       target_date      DATE,
                       outdoor          BOOLEAN        NOT NULL DEFAULT FALSE,
                       status           VARCHAR(20)    NOT NULL DEFAULT 'ACTIVE',
                       category_id      BIGINT         NOT NULL REFERENCES categories (id),
                       template_id      BIGINT         REFERENCES goal_templates (id),
                       motivation       VARCHAR(500),
                       icon_key         VARCHAR(50),
                       color            VARCHAR(7),
                       version          BIGINT         NOT NULL DEFAULT 0,
                       created_at       TIMESTAMP      NOT NULL,
                       updated_at       TIMESTAMP      NOT NULL,
                       archived_at      TIMESTAMP,
                       CONSTRAINT ck_goals_tracking CHECK (tracking_type IN ('CHECK', 'AMOUNT')),
                       CONSTRAINT ck_goals_period CHECK (period IS NULL OR period IN ('DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY')),
                       CONSTRAINT ck_goals_status CHECK (status IN ('ACTIVE', 'ARCHIVED')),
                       CONSTRAINT ck_goals_times CHECK (times_per_period IS NULL OR times_per_period > 0),
                       CONSTRAINT ck_goals_amount CHECK (target_amount IS NULL OR target_amount > 0),
                       CONSTRAINT ck_goals_dates CHECK (target_date IS NULL OR start_date IS NULL OR target_date >= start_date),
                       CONSTRAINT ck_goals_shape CHECK (
                           (tracking_type = 'CHECK' AND period IS NOT NULL AND times_per_period IS NOT NULL)
                               OR
                           (tracking_type = 'AMOUNT' AND target_amount IS NOT NULL AND unit IS NOT NULL
                               AND (period IS NOT NULL OR target_date IS NOT NULL))
                           )
);

CREATE INDEX idx_goals_user_status   ON goals (user_id, status);
CREATE INDEX idx_goals_user_category ON goals (user_id, category_id);